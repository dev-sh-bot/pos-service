export function sndIconMarkup(name, { className = "", style = "", id = "" } = {}) {
    const attributes = [
        `class="snd-icon${className ? ` ${className}` : ""}"`,
        id ? `id="${id}"` : "",
        style ? `style="${style}"` : "",
    ].filter(Boolean).join(" ");

    return `<svg ${attributes} width="1em" height="1em" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${SVG_NODES[name] || SVG_NODES.user}</svg>`;
}

export default function SndIcon({ name = "circle-check", size = "1em", strokeWidth = 2, ...props }) {
    const Icon = ICONS[name] || CircleCheck;

    return <Icon aria-hidden="true" size={size} strokeWidth={strokeWidth} {...props} />;
}
